import { Inject, Injectable, NotFoundException } from "@nestjs/common";
import type { z } from "zod4";
import { RcaApiService } from "../../../detection/detections/application/rca.api";
import { clip } from "../domain/clip";
import { available, empty, unavailable } from "../domain/evidence-result";
import { getRcaSchema } from "../infrastructure/investigation-tools.schemas";
import type { ToolScope } from "../domain/investigation-tools.types";

@Injectable()
export class RcaInvestigation {
  constructor(@Inject(RcaApiService) private readonly rca: RcaApiService) {}

  async getLatest({ orgId, projectId }: ToolScope, args: z.infer<typeof getRcaSchema>) {
    try {
      const row = await this.rca.getLatest(orgId, projectId, args.findingId);
      if (!row) {
        return empty<never>("No root cause analysis has been generated for this finding yet. It can be generated from the Soonwhy dashboard.");
      }
      return available({
        findingId: row.findingId,
        service: row.serviceName,
        severity: row.severity,
        summary: clip(row.summary, 1_000),
        rootCause: clip(row.rootCause, 1_500),
        contributingFactors: row.contributingFactors,
        investigationSteps: row.investigationSteps,
        suggestedChanges: row.suggestedChanges,
        limitations: row.limitations,
        confidence: row.confidence,
        model: row.model,
        generatedAt: row.createdAt,
        note: "Generated by a model from detector evidence. Treat it as a hypothesis, not a confirmed cause.",
      });
    } catch (error) {
      if (error instanceof NotFoundException) return unavailable("No finding with this id in this project.");
      return unavailable("The query failed. This is not the same as no results.");
    }
  }
}
